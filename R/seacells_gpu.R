## implementation --------------------------------------------------------------

#' Shared implementation of the GPU SEACells generation
#'
#' @description
#' Body behind both `generate_seacells_gpu_sc()` methods. Pulls the embedding
#' and the cached kNN graph off the object, hands them to [rs_seacells_gpu()]
#' and wraps the result into a [bixverse::MetaCells()].
#'
#' @inheritParams generate_seacells_gpu_sc
#'
#' @returns A [bixverse::MetaCells()].
#'
#' @keywords internal
.generate_seacells_gpu <- function(
  object,
  seacell_params,
  embd_to_use,
  no_embd_to_use,
  cells_to_use,
  regenerate_knn,
  target_size,
  seed,
  .verbose
) {
  # checks
  checkmate::assertTRUE(
    S7::S7_inherits(object, bixverse::SingleCells) ||
      S7::S7_inherits(object, bixverse::SingleCellsSubset)
  )
  bixverse:::assertScSeacells(seacell_params)
  checkmate::qassert(embd_to_use, "S1")
  checkmate::qassert(no_embd_to_use, c("I1", "0"))
  checkmate::qassert(cells_to_use, c("S+", "0"))
  checkmate::qassert(regenerate_knn, "B1")
  checkmate::qassert(target_size, "N1")
  checkmate::qassert(seed, "I1")
  checkmate::qassert(.verbose, c("B1", "I1[0,2]"))

  # hard tier: cell indices from here go straight into Rust
  bixverse::assert_sc_state(
    object,
    artefacts = c(embd_to_use, if (!regenerate_knn) "knn")
  )

  # function body
  embd <- bixverse::get_embedding(x = object, embd_name = embd_to_use)

  if (!is.null(no_embd_to_use)) {
    to_take <- min(c(no_embd_to_use, ncol(embd)))
    embd <- embd[, 1:to_take]
  }

  if (!is.null(cells_to_use)) {
    cells_to_use <- bixverse::get_cell_indices(
      object,
      cell_ids = cells_to_use,
      rust_index = TRUE
    )
  }

  knn_data <- if (regenerate_knn) {
    NULL
  } else {
    bixverse::get_knn_obj(object)
  }

  seacell_data <- rs_seacells_gpu(
    f_path = bixverse:::get_rust_count_cell_f_path(object),
    embd = embd,
    cells_to_use = cells_to_use,
    cells_to_keep = bixverse::get_cells_to_keep(object),
    knn_data = knn_data,
    seacells_params = seacell_params,
    target_size = target_size,
    seed = seed,
    verbose = bixverse:::parse_verbosity(.verbose)
  )

  var_data <- bixverse::get_sc_var(object, cols = c("gene_idx", "gene_id"))

  bixverse::MetaCells(
    meta_cell_data = seacell_data,
    var_data = var_data,
    meta_cell_method = "seacell"
  )
}
